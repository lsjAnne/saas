CREATE TABLE IF NOT EXISTS channel_auth_state (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    channel_type VARCHAR(32) NOT NULL,
    channel_account_id BIGINT,
    state VARCHAR(128) NOT NULL,
    redirect_uri VARCHAR(512),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_channel_auth_state UNIQUE (state)
);

CREATE INDEX IF NOT EXISTS idx_channel_auth_state_expires ON channel_auth_state (expires_at);

CREATE TABLE IF NOT EXISTS channel_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    channel_type VARCHAR(32) NOT NULL,
    account_name VARCHAR(128) NOT NULL,
    access_token TEXT NOT NULL,
    refresh_token TEXT,
    token_type VARCHAR(32),
    scope VARCHAR(256),
    expires_at TIMESTAMP,
    refresh_expires_at TIMESTAMP,
    extra_config TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_channel_token_org_type_account UNIQUE (organization_id, channel_type, account_name)
);

CREATE INDEX IF NOT EXISTS idx_channel_token_tenant ON channel_token (tenant_id, channel_type);
