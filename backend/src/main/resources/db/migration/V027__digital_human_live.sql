CREATE TABLE IF NOT EXISTS digital_human_avatar (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    avatar_name VARCHAR(128) NOT NULL,
    avatar_type VARCHAR(32) NOT NULL,
    voice_name VARCHAR(128),
    preview_url VARCHAR(512),
    enabled SMALLINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_dh_avatar_tenant ON digital_human_avatar (tenant_id, enabled);

CREATE TABLE IF NOT EXISTS digital_human_script (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    script_name VARCHAR(128) NOT NULL,
    scene_type VARCHAR(32) NOT NULL,
    content_text TEXT NOT NULL,
    version VARCHAR(16) NOT NULL DEFAULT 'v1',
    status VARCHAR(16) NOT NULL DEFAULT 'draft',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_dh_script_tenant ON digital_human_script (tenant_id, status);

CREATE TABLE IF NOT EXISTS digital_human_schedule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    schedule_name VARCHAR(128) NOT NULL,
    avatar_id BIGINT NOT NULL,
    script_id BIGINT NOT NULL,
    platform_type VARCHAR(32) NOT NULL,
    repeat_type VARCHAR(16) NOT NULL DEFAULT 'once',
    start_at TIMESTAMP NOT NULL,
    end_at TIMESTAMP,
    enabled SMALLINT NOT NULL DEFAULT 1,
    status VARCHAR(16) NOT NULL DEFAULT 'scheduled',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_dh_schedule_tenant ON digital_human_schedule (tenant_id, status);

CREATE TABLE IF NOT EXISTS digital_human_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    schedule_id BIGINT,
    avatar_id BIGINT,
    platform_room_id VARCHAR(128),
    live_status VARCHAR(16) NOT NULL DEFAULT 'scheduled',
    started_at TIMESTAMP,
    ended_at TIMESTAMP,
    viewer_peak BIGINT NOT NULL DEFAULT 0,
    order_count BIGINT NOT NULL DEFAULT 0,
    gmv_amount DECIMAL(18, 2) NOT NULL DEFAULT 0,
    heartbeat_at TIMESTAMP,
    mock_flag SMALLINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_dh_session_tenant ON digital_human_session (tenant_id, live_status);
