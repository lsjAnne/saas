CREATE TABLE IF NOT EXISTS digital_human_faq (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    product_id VARCHAR(64),
    product_name VARCHAR(128),
    question_type VARCHAR(32) NOT NULL DEFAULT 'generic',
    keywords VARCHAR(512),
    question VARCHAR(256) NOT NULL,
    answer VARCHAR(512) NOT NULL,
    enabled SMALLINT NOT NULL DEFAULT 1,
    hit_count BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_dh_faq_tenant ON digital_human_faq (tenant_id, enabled);
CREATE INDEX IF NOT EXISTS idx_dh_faq_product ON digital_human_faq (tenant_id, product_id, question_type);

CREATE TABLE IF NOT EXISTS digital_human_barrage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    session_id VARCHAR(64),
    platform_type VARCHAR(32) NOT NULL,
    user_nick VARCHAR(64),
    content VARCHAR(256) NOT NULL,
    reply_status VARCHAR(16) NOT NULL DEFAULT 'pending',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_dh_barrage_tenant ON digital_human_barrage (tenant_id, session_id);

CREATE TABLE IF NOT EXISTS digital_human_interaction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    session_id VARCHAR(64),
    barrage_id VARCHAR(64),
    hit_type VARCHAR(16) NOT NULL,
    faq_id VARCHAR(64),
    question VARCHAR(256) NOT NULL,
    answer VARCHAR(512) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_dh_interaction_tenant ON digital_human_interaction (tenant_id, session_id);
