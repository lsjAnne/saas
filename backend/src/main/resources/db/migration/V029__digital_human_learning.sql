CREATE TABLE IF NOT EXISTS digital_human_learning_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    session_id VARCHAR(64),
    question VARCHAR(256) NOT NULL,
    question_type VARCHAR(32) NOT NULL,
    product_name VARCHAR(128),
    occurrence_count BIGINT NOT NULL DEFAULT 1,
    status VARCHAR(16) NOT NULL DEFAULT 'new',
    faq_id VARCHAR(64),
    last_seen_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_dh_learning_tenant ON digital_human_learning_item (tenant_id, status);
CREATE INDEX IF NOT EXISTS idx_dh_learning_faq ON digital_human_learning_item (tenant_id, faq_id);

